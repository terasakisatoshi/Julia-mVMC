using Test, Random, SHA
using MVMCOptimizers, MVMCExpertModeParsers
using MVMCExpertModeParsers: ExpertModeData, ModParaParameters

# A literal primitive tape, not a replacement sampler/proposal/acceptance.
# All UInt32 values are 2^31: spin=down, modulo Ne=0, Metropolis=1/2.
mutable struct ExchangeCounterTape <: AbstractRNG
    raw::Vector{UInt32}
    cursor::Int
    count::UInt128
end
Random.rand(rng::ExchangeCounterTape, ::Type{UInt32}) = begin
    word = rng.raw[rng.cursor + 1]
    rng.cursor += 1
    rng.count += 1
    word
end

function exchange_counter_hand_fixture(complex, case)
    data = ExpertModeData()
    data.modpara = ModParaParameters(nsite = 2, nelec = 1, nvmc_sample = 1,
        nvmc_warmup = 0, nvmc_interval = 1, nex_update_path = 2)
    data.qp_weights = MVMCExpertModeParsers.QuantumProjectionWeights()
    data.qp_weights.qp_full_weight = ComplexF64[1]
    state = MVMCOptimizers.VMCOptimizationState(2, 1, 0, 0, 1, 1, complex, false)
    # Two-by-two occupied Pfaffian: initial amplitude 1; exchanged amplitude
    # 1 (always accept) or 0 (always reject at Metropolis=1/2).
    A = zeros(4, 4)
    for (i, j, value) in ((1, 4, 1.0), (2, 3, case == :metropolis_reject ? 0.0 : 1.0),
                           (1, 3, 1.0))
        A[i, j] = value
        A[j, i] = -value
    end
    state.slater_matrix.slater_elm .= vec(permutedims(A))
    if !complex
        state.slater_matrix.slater_elm_real .= vec(permutedims(A))
    end
    config = state.electron_config
    config.tmp_ele_idx .= case == :candidate_reject ? [0, 0] : [0, 1]
    fill!(config.tmp_ele_cfg, -1)
    fill!(config.tmp_ele_num, 0)
    for spin in 0:1
        site = config.tmp_ele_idx[spin + 1]
        config.tmp_ele_cfg[site + 2spin + 1] = 0
        config.tmp_ele_num[site + 2spin + 1] = 1
    end
    MVMCOptimizers.copy_to_burn_sample!(config.tmp_ele_idx, config.tmp_ele_cfg,
        config.tmp_ele_num, config.tmp_ele_proj_cnt, state)
    resize!(config.counter, 11)
    fill!(config.counter, 0)
    config.counter[11] = 1
    return data, state, ExchangeCounterTape(fill(UInt32(0x80000000), 624), 0, 0)
end

# Recover ONLY the four counter statements and verify the entire prepatch
# source hash before compiling renamed originals. No old numerical override,
# dispatch replacement, or fixture generated by Rust is involved.
function exchange_counter_originals()
    source = read(joinpath(@__DIR__, "..", "src", "vmc_sampling.jl"), String)
    original = source
    for name in ("vmc_make_sample!", "vmc_make_sample_real!")
        start = findfirst("function " * name * "(", original)
        tail = SubString(original, first(start))
        stop = findfirst("\nend", tail)
        body = String(SubString(tail, 1, last(stop)))
        old = replace(body,
            "                state.electron_config.counter[3] += 1\n" => "",
            "                    state.electron_config.counter[4] += 1\n" => "")
        original = replace(original, body => old; count = 1)
    end
    @test bytes2hex(sha256(original)) ==
        "6cf602be483f967de71b253fead910d92d3583bea7f9b02caccabad2c7c4deb0"
    functions = Function[]
    for name in ("vmc_make_sample!", "vmc_make_sample_real!")
        start = findfirst("function " * name * "(", original)
        tail = SubString(original, first(start))
        stop = findfirst("\nend", tail)
        expr = Meta.parse(String(SubString(tail, 1, last(stop))))
        signature = expr.args[1]
        call = signature.head == :where ? signature.args[1] : signature
        call.args[1] = Symbol(name * "_exchange_counter_original")
        Core.eval(MVMCOptimizers, expr)
        push!(functions, getfield(MVMCOptimizers, call.args[1]))
    end
    return functions
end

@testset "ordinary exchange C attempt/accept/reject behavior" begin
    originals = exchange_counter_originals()
    for (index, complex) in enumerate((true, false)),
        case in (:accept, :candidate_reject, :metropolis_reject)
        data, state, rng = exchange_counter_hand_fixture(complex, case)
        old_data, old_state, old_rng = exchange_counter_hand_fixture(complex, case)
        sampler = complex ? MVMCOptimizers.vmc_make_sample! : MVMCOptimizers.vmc_make_sample_real!
        Base.invokelatest(originals[index], old_data, old_state, old_rng)
        sampler(data, state, rng)
        # C loop: burn resume => (Nsample+1)*Ninterval*Nsite = 4 attempts.
        # Candidate rejection draws nothing; valid exchange consumes mi/spin/mj
        # plus one Metropolis word per attempt. No selected-path choice draw.
        expected_accept = case == :accept ? 4 : 0
        expected_draws = case == :candidate_reject ? 0 : 16
        @test state.electron_config.counter[1:4] == [0, 0, 4, expected_accept]
        @test old_state.electron_config.counter[1:4] == [0, 0, 0, 0]
        @test rng.raw == old_rng.raw
        @test rng.cursor == old_rng.cursor == expected_draws
        @test rng.count == old_rng.count == UInt128(expected_draws)
        @test rng.raw[(rng.cursor + 1):end] == old_rng.raw[(old_rng.cursor + 1):end]
        for field in fieldnames(typeof(state.electron_config))
            field == :counter && continue
            @test getfield(state.electron_config, field) == getfield(old_state.electron_config, field)
        end
        @test state.electron_config.ele_idx == (case == :candidate_reject ? [0, 0] : [0, 1])
        @test state.electron_config.counter[5:end] == old_state.electron_config.counter[5:end]
        # Numeric arrays are diagnostic here; independently identical arithmetic
        # is guarded by the full reconstructed-source hash above. No fitted
        # floating tolerance or cross-provider bitwise-parity assertion.
        for field in fieldnames(typeof(state.slater_matrix))
            values = getfield(state.slater_matrix, field)
            baseline = getfield(old_state.slater_matrix, field)
            println("EXCHANGE_NUMERIC case=", case, " complex=", complex,
                " field=", field, " maxdiff=", isempty(values) ? 0 : maximum(abs.(values .- baseline)))
        end
    end
end
